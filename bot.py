@dp.message(lambda message: message.photo)
async def handle_image(message: Message):
    """Handle image messages"""
    # Show processing message
    processing_msg = await message.answer(
        "🔄 *Analyzing image...*\nPlease wait 5-10 seconds.",
        parse_mode=ParseMode.MARKDOWN
    )
    
    image_path = None
    
    try:
        # Download image
        image_path = await download_image(message)
        logger.info(f"Image downloaded: {image_path}")
        
        # Analyze image
        result = await analyzer.analyze(image_path)
        
        # Format and send result
        result_text = format_analysis_result(result)
        await message.answer(result_text, parse_mode=ParseMode.MARKDOWN)
        
        # Delete processing message
        await processing_msg.delete()
        
    except ValueError as e:
        await processing_msg.delete()
        await message.answer(f"❌ *Error:* {str(e)}", parse_mode=ParseMode.MARKDOWN)
        
    except Exception as e:
        logger.error(f"Error processing image: {e}")
        await processing_msg.delete()
        await message.answer(
            "❌ *Error:* Failed to analyze image. Please try again with a different image.",
            parse_mode=ParseMode.MARKDOWN
        )
        
    finally:
        # Clean up temporary file
        if image_path and os.path.exists(image_path):
            try:
                os.unlink(image_path)
                logger.info(f"Cleaned up: {image_path}")
            except Exception as e:
                logger.error(f"Error cleaning up {image_path}: {e}")

@dp.message()
async def handle_other(message: Message):
    """Handle non-image messages"""
    await message.answer(
        "📸 Please send me an image to analyze.\n\n"
        "Use /help to see available commands."
    )

async def periodic_cleanup():
    """Run cleanup every hour"""
    while True:
        await asyncio.sleep(3600)  # 1 hour
        await cleanup_temp_files()

async def main():
    """Main bot entry point"""
    # Start periodic cleanup task
    asyncio.create_task(periodic_cleanup())
    
    # Start polling
    logger.info("Bot started!")
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())